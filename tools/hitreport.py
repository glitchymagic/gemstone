#!/usr/bin/env python3
"""docs/HITS.md: per fighter, every attack action of the remaster and where its hit comes from (pass 4).
  game spheres   = the game's hit steps arm a hit id and attack spheres (limbs + radius + frames), its record's damage
  game record    = the steps arm a hit id but the game delivers it with a projectile / effect object (not decoded):
                   the remaster keeps its own reach volume and uses the game's record damage
  remaster       = no hit data for the motion (the remaster's own numbers)
  logged         = that motion landed hits in a logged real fight and the formula matched every one (tools/hitlog.py)
Usage: hitreport.py [CAPTURE_NAME ...]   (default hdA + every hlSlogN)"""
import json, sys
sys.path.insert(0, './tools')
import hitdata as H
R = './'
NAMES = ['Falcon', 'Ryoma', 'Wang-Tang', 'Jack', 'Gunrock', 'Galuda', 'Ayame', 'Rouge', 'Kraken', 'Valgas', 'Final Valgas']
ACTS = ['punch1', 'punch2', 'punch3', 'punch4', 'kick1', 'kick2', 'kick3', 'dash', 'dash_k', 'air', 'air_k', 'drive_p',
        'drive_k', 'drive_k2', 'air_drive_p', 'air_drive_k', 'fusion1', 'fusion2', 'fusion2_b', 'fusion2_c', 'pole_swing',
        'pole_launch', 'pole_kick', 'throw']
# joint labels: every fighter (both forms) has the same joints 0-18 (rip/skel parents): 1 chest, 2 hips, 3 neck, 4 head,
# 5/9 shoulders, 6/10 upper arms, 7/11 forearms (origin at the elbow), 8/12 hands, 13/16 thighs, 14/17 shins (knee),
# 15/18 feet; which side is which isn't decoded, so the joint number stays in the label
JOINTS = {1: 'chest', 2: 'hips', 3: 'neck', 4: 'head', 5: 'shoulder5', 6: 'upperarm6', 7: 'forearm7', 8: 'hand8',
          9: 'shoulder9', 10: 'upperarm10', 11: 'forearm11', 12: 'hand12', 13: 'thigh13', 14: 'shin14', 15: 'foot15',
          16: 'thigh16', 17: 'shin17', 18: 'foot18', 255: 'body'}


def logged_moves(names):
    sys.path.insert(0, R + 'tools')
    import hitlog
    ok = set()
    for n in names:
        try:
            for r in hitlog.hits(n):
                if r['pred'] is not None and r['pred'] == r['dmg']:
                    ok.add((r['ach'], f"k{r['move'][0]}_{r['move'][1]:03d}"))
        except OSError:
            pass
    return ok


def main(names):
    logged = logged_moves(names)
    out = ['# Hits: what comes from the game (pass 4)', '',
           'Generated by tools/hitreport.py from game/assets/ripped/pN0_hit.json (tools/hitdata.py export: Pn0_HIT.BIN '
           'steps, 1ST_READ attack records and PL sphere sets) and the logged fights ' + ', '.join(names) + '.', '',
           'Damage is on the game\'s 240-point health before the multipliers (Rules.game_damage). Frames are motion '
           'frames from the start of the move (60 per second). **logged** = this motion landed hits in a logged '
           'real fight and the damage formula matched every one.', '']
    counts = {'game spheres': 0, 'game record': 0, 'remaster': 0}
    for n in range(11):
        j = json.load(open(R + f'game/assets/ripped/{H.pname(n).lower()}_hit.json'))
        try:
            cm = json.load(open(R + f'game/assets/ripped/{H.pname(n).lower()}_clips.json'))['map']
        except OSError:
            continue
        out += [f'## {NAMES[n]} ({H.pname(n)}, takes x{j["defence"]} damage)', '',
                '| action | motion | source | frames live | limbs (sphere radius cm) | base damage | logged |',
                '|---|---|---|---|---|---|---|']
        for a in ACTS:
            if a not in cm: continue
            key = cm[a][cm[a].find('k'):]
            st = j['moves'].get(key, [])
            hid = next((s[2] for s in st if s[2]), 0) or j.get('code_hits', {}).get(key, 0)
            live = [(s[0], s[0] + min(s[1], 254) - 1, s[3]) for s in st if s[3] and str(s[3]) in j['atk_sets']]
            if a == 'throw':
                src, fr, limbs = 'game record (throw code, type 2)', '', ''
                rec = j['hits'].get('50', {}); dmg = rec.get('dmg', '') if NAMES[n] in ('Falcon', 'Wang-Tang') else '48 (remaster: not logged)'
            elif hid and live:
                src = 'game spheres'; counts['game spheres'] += 1
                fr = ', '.join(f'{x}-{y}' if y < 200 else f'{x}-end' for x, y, _ in live)
                sets = sorted({s for _, _, s in live})
                limbs = '; '.join(', '.join(f"{JOINTS.get(jt, jt)} {j['spheres'][str(e)][3]}" for jt, e in j['atk_sets'][str(s)]
                                            if j['spheres'].get(str(e), [0, 0, 0, 0])[3]) for s in sets)
                dmg = j['hits'].get(str(hid), {}).get('dmg', '')
            elif hid:
                src = 'game record, remaster reach'; counts['game record'] += 1
                fr, limbs = '', '(projectile / effect)'
                dmg = j['hits'].get(str(hid), {}).get('dmg', '')
            else:
                src, fr, limbs, dmg = 'remaster', '', '', ''; counts['remaster'] += 1
            lg = 'yes' if (n, key) in logged else ''
            out.append(f'| {a} | {key} | {src} | {fr} | {limbs} | {dmg} | {lg} |')
        out.append('')
    out.insert(6, f"Totals over all fighters: {counts['game spheres']} actions hit with the game's spheres, "
                  f"{counts['game record']} with the game's record but the remaster's reach, {counts['remaster']} "
                  f"still the remaster's own numbers. Logged exact: {len(logged)} motions.")
    out.insert(7, '')
    open(R + 'docs/HITS.md', 'w').write('\n'.join(out) + '\n')
    print(out[6])


if __name__ == '__main__':
    import glob, os
    caps = sorted(os.path.basename(f)[:-4] for f in glob.glob(R + 'dumps/cap/hlSlog*.bin'))
    main(sys.argv[1:] or ['hdA'] + caps)
